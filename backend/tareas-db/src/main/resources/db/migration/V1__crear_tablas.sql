CREATE TABLE tarea (
   id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   titulo      VARCHAR(200) NOT NULL,
   completada  BOOLEAN      NOT NULL DEFAULT FALSE,
   creada_en   TIMESTAMPTZ  NOT NULL DEFAULT now(),

   CONSTRAINT chk_tarea_titulo_no_vacio CHECK (length(trim(titulo)) > 0)
);

COMMENT ON TABLE  tarea            IS 'Tareas del usuario';
COMMENT ON COLUMN tarea.completada IS 'TRUE cuando la tarea fue marcada como hecha';